const fs=require('node:fs');
const path=require('node:path');
const {extractReferences}=require('./apps-script/Code.js');
const formulas=require('./data/formulas.json');
const lines=['# Formula inventory','','Generated by `node inventory.cjs`. Explicit cross-sheet references only; same-sheet dependencies and external consumers require review.','','| Consumer | Formula | Detected source |','|---|---|---|'];
for(const [sheet,items] of Object.entries(formulas)) items.forEach((f,i)=>{
  const refs=extractReferences(f).refs.map(r=>r.sheet+'!'+r.range).join(', ')||'Same-sheet references; inspect formula';
  lines.push('| '+sheet+'!B'+(i+2)+' | `'+f+'` | '+refs+' |');
});
fs.writeFileSync(path.join(__dirname,'docs','formula-inventory.md'),lines.join('\n')+'\n');
console.log('Inventoried 16 formulas. External consumers remain unknown.');
